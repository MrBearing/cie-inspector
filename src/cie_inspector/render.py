"""Human-readable renderers (table format)."""

from __future__ import annotations

from cie_inspector.models import Confidence, Inventory, ScanReport


def _format_table(headers: list[str], rows: list[list[str]]) -> str:
    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(cell))
    lines = [
        "  ".join(h.ljust(w) for h, w in zip(headers, widths, strict=True)).rstrip(),
        "  ".join("-" * w for w in widths),
    ]
    for row in rows:
        lines.append("  ".join(c.ljust(w) for c, w in zip(row, widths, strict=True)).rstrip())
    return "\n".join(lines)


def render_scan_table(report: ScanReport) -> str:
    rows: list[list[str]] = []
    n_unresolved = 0
    for pkg in report.packages:
        n_unresolved += len(pkg.unresolved)
        for exe in pkg.executables:
            n_unresolved += len(exe.unresolved)
            rows.append([pkg.name, exe.name, exe.kind, ", ".join(exe.sources) or "-"])
        for ep in pkg.python_entry_points:
            rows.append([pkg.name, ep.name, "python (unsupported)", ep.target])
        if not pkg.executables and not pkg.python_entry_points:
            rows.append([pkg.name, "-", "-", "-"])
    table = _format_table(["PACKAGE", "EXECUTABLE", "KIND", "SOURCES"], rows)
    summary = (
        f"\n{len(report.packages)} package(s), "
        f"{sum(len(p.executables) for p in report.packages)} executable(s), "
        f"{n_unresolved} unresolved item(s)"
    )
    return table + summary


def render_inventory_table(inventory: Inventory) -> str:
    rows: list[list[str]] = []
    n_members = 0
    n_unresolved = len(inventory.scan_unresolved) + len(inventory.unmatched_launch_nodes)
    for node in inventory.nodes:
        n_unresolved += len(node.unresolved)
        label = f"{node.package}/{node.executable}"
        if node.launch is not None:
            ns = node.launch.namespace.rstrip("/")
            label += f" [{ns}/{node.launch.node_name}]"
        first = True
        for group in node.callback_groups:
            n_members += len(group.members)
            flag = "" if group.confidence is Confidence.resolved else f" ({group.confidence.value})"
            rows.append(
                [label if first else "", group.id, group.type + flag, str(len(group.members))]
            )
            first = False
        if first:
            rows.append([label, "-", "-", "0"])
    table = _format_table(["NODE", "GROUP", "TYPE", "MEMBERS"], rows)
    summary = (
        f"\n{len(inventory.nodes)} node(s), "
        f"{sum(len(n.callback_groups) for n in inventory.nodes)} group(s), "
        f"{n_members} member(s), {n_unresolved} unresolved item(s)"
    )
    if inventory.unsupported:
        summary += f", {len(inventory.unsupported)} unsupported (python) node(s)"
    if inventory.unmatched_launch_nodes:
        summary += "\nunmatched launch nodes: " + ", ".join(
            f"{u.package}/{u.executable}" for u in inventory.unmatched_launch_nodes
        )
    return table + summary


def _cie_member_token(member) -> str | None:
    """One `@Callback(...)` element of a cie_thread_configurator group id."""
    if member.kind == "subscription":
        topic = member.resolved_topic or member.declared_topic
        return f"Subscription({topic})" if topic else "Subscription(<unresolved>)"
    if member.kind == "timer":
        if member.period_ns is not None:
            return f"Timer({member.period_ns})"
        return "Timer(<unresolved>)"
    if member.kind == "service":
        name = member.resolved_topic or member.declared_topic
        return f"Service({name})" if name else "Service(<unresolved>)"
    if member.kind == "client":
        name = member.resolved_topic or member.declared_topic
        return f"Client({name})" if name else "Client(<unresolved>)"
    return None  # publishers never appear in group ids


def render_cie_yaml(inventory: Inventory) -> str:
    """Thread-configuration skeleton in tier4/callback_isolated_executor
    (cie_thread_configurator) format. Scheduling values are TODO on purpose:
    choosing them is the human's job."""
    from cie_inspector import CLI_NAME, __version__

    lines = [
        f"# Thread configuration skeleton generated by {CLI_NAME} {__version__}",
        "# Format: tier4/callback_isolated_executor (cie_thread_configurator)",
        "# Fill in policy / priority / affinity for every callback group.",
        "# Group ids are reconstructed statically and are best-effort:",
        "# verify them against the ids emitted by the CIE prerun tool.",
        "callback_groups:",
    ]
    entries = 0
    for node in inventory.nodes:
        if node.launch is not None:
            ns = node.launch.namespace.rstrip("/")
            node_path = f"{ns}/{node.launch.node_name}"
            name_note = None
        elif node.node_name is not None:
            node_path = f"/{node.node_name}"
            name_note = "node name taken from source; launch may override it"
        else:
            node_path = f"/<TODO:{node.executable}>"
            name_note = "node name could not be determined statically"
        for group in node.callback_groups:
            tokens = [_cie_member_token(m) for m in group.members]
            tokens = [t for t in tokens if t is not None]
            if not tokens:
                continue
            entries += 1
            comment = f"{node.package}/{node.executable}  group: {group.id} ({group.type})"
            if group.declared_at:
                comment += f"  {group.declared_at}"
            lines.append(f"  # {comment}")
            if name_note:
                lines.append(f"  # TODO: {name_note}")
            lines.append(f"  - id: {node_path}@{'@'.join(tokens)}")
            lines.append("    policy: TODO  # SCHED_OTHER | SCHED_FIFO | SCHED_RR | SCHED_DEADLINE")
            lines.append("    priority: TODO  # FIFO/RR: 1-99 (99 highest); CFS: nice -20..19")
            lines.append("    affinity: TODO  # CPU core list, e.g. [2, 3]; ~ allows all cores")
    if entries == 0:
        lines.append("  []  # no callback groups with members were found")
    return "\n".join(lines) + "\n"
